WITH league_context AS (
    SELECT DISTINCT ON (it.player_id, it.extraction_date, it.source)
           it.player_id, it.extraction_date, it.source, it.id AS run_item_id,
           c.id AS context_id, c.provider_competition_id, c.provider_team_id,
           c.season_key, c.season_label
    FROM player_statistics_run_items it
    JOIN player_performance_contexts c ON c.run_item_id = it.id
    JOIN players p ON p.id = it.player_id
    JOIN teams tm ON tm.id = p.team_id
    JOIN (VALUES (1::bigint, 2), (2, 3), (3, 4), (4, 5), (5, 22)) AS m(league_id, tournament_id)
      ON m.league_id = tm.league_id
     AND m.tournament_id = c.provider_competition_id::int
    ORDER BY it.player_id, it.extraction_date, it.source,
             c.season_key::bigint DESC NULLS LAST, c.id
)
