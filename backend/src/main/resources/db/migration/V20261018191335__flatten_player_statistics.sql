-- Una fila por jugador, campana y canal: las 60 metricas del catalogo en columnas.
-- El contexto se limita a la liga local del jugador, de modo que nunca se suman contextos
-- distintos. La fuente forma parte de la clave, de modo que JSON y scraping no se pisan.
--
-- El mapeo liga local -> tournament de WhoScored queda congelado aqui con los valores de
-- configuracion vigentes (1->2, 2->3, 3->4, 4->5, 5->22). La seleccion de contexto en el codigo
-- lee esa misma configuracion, no esta migracion.

