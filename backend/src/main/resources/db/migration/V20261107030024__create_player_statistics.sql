CREATE SEQUENCE player_statistics_id_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE player_statistics (
    id BIGINT PRIMARY KEY DEFAULT nextval('player_statistics_id_seq'),
    player_id BIGINT NOT NULL REFERENCES players(id),
    extraction_date DATE NOT NULL,
    source VARCHAR(32) NOT NULL,
    provider_competition_id VARCHAR(255),
    provider_team_id VARCHAR(255),
    season_key VARCHAR(255),
    season_label VARCHAR(255),
    context_status VARCHAR(32) NOT NULL,
    run_item_id BIGINT REFERENCES player_statistics_run_items(id),
    observed_at TIMESTAMPTZ NOT NULL,
    present_metrics INTEGER NOT NULL DEFAULT 0,
    absent_metrics INTEGER NOT NULL DEFAULT 0,
    minutes_played_total NUMERIC,
    appearances_total NUMERIC,
    goals_total NUMERIC,
    assists_total NUMERIC,
    shots_per_match NUMERIC,
    pass_completion_percentage NUMERIC,
    aerial_duels_won_per_match NUMERIC,
    yellow_cards_total NUMERIC,
    red_cards_total NUMERIC,
    tackles_per_match NUMERIC,
    interceptions_per_match NUMERIC,
    clearances_per_match NUMERIC,
    blocked_shots_per_match NUMERIC,
    dribbled_past_per_match NUMERIC,
    offsides_won_per_match NUMERIC,
    own_goals_total NUMERIC,
    saves_per_match NUMERIC,
    six_yard_box_saves_per_match NUMERIC,
    penalty_area_saves_per_match NUMERIC,
    outside_box_saves_per_match NUMERIC,
    attempted_tackles_per_match NUMERIC,
    blocked_crosses_per_match NUMERIC,
    blocked_passes_per_match NUMERIC,
    failed_dribbles_per_match NUMERIC,
    total_dribbles_per_match NUMERIC,
    aerial_duels_lost_per_match NUMERIC,
    total_aerial_duels_per_match NUMERIC,
    inaccurate_long_balls_per_match NUMERIC,
    accurate_short_passes_per_match NUMERIC,
    inaccurate_short_passes_per_match NUMERIC,
    long_key_passes_per_match NUMERIC,
    short_key_passes_per_match NUMERIC,
    six_yard_box_shots_per_match NUMERIC,
    penalty_area_shots_per_match NUMERIC,
    outside_box_shots_per_match NUMERIC,
    six_yard_box_goals_per_match NUMERIC,
    penalty_area_goals_per_match NUMERIC,
    outside_box_goals_per_match NUMERIC,
    cross_assists_per_match NUMERIC,
    corner_assists_per_match NUMERIC,
    through_ball_assists_per_match NUMERIC,
    free_kick_assists_per_match NUMERIC,
    throw_in_assists_per_match NUMERIC,
    other_assists_per_match NUMERIC,
    fouls_committed_per_match NUMERIC,
    goals_per_match NUMERIC,
    assists_per_match NUMERIC,
    whoscored_rating_average NUMERIC,
    shots_on_target_total NUMERIC,
    second_yellow_total NUMERIC,
    starts_total NUMERIC,
    substitute_appearances_total NUMERIC,
    key_passes_per_match NUMERIC,
    successful_dribbles_per_match NUMERIC,
    offsides_per_match NUMERIC,
    dispossessed_per_match NUMERIC,
    bad_controls_per_match NUMERIC,
    passes_per_match NUMERIC,
    successful_long_balls_per_match NUMERIC,
    successful_crosses_per_match NUMERIC,
    CONSTRAINT uq_player_statistics UNIQUE (extraction_date, source, player_id),
    CONSTRAINT ck_player_statistics_context
        CHECK (context_status IN ('RESOLVED', 'NO_LEAGUE_CONTEXT')),
    CONSTRAINT ck_player_statistics_counts
        CHECK (present_metrics >= 0 AND absent_metrics >= 0)
);

ALTER SEQUENCE player_statistics_id_seq OWNED BY player_statistics.id;
CREATE INDEX ix_player_statistics_player
    ON player_statistics(player_id, extraction_date DESC);
CREATE INDEX ix_player_statistics_campaign
    ON player_statistics(extraction_date, source);
